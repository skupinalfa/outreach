def get_sheet_data_by_path(file_path, sheet_name='Sheet1'):
    """
    Loads a Google Sheet document by extracting its name from a given file path
    (assuming the file path points to a .gsheet shortcut file) and returns it
    as a pandas DataFrame.

    Args:
        file_path (str): The path to the .gsheet shortcut file in Google Drive.
                         Example: '/content/drive/MyDrive/Folder/YourSheet.gsheet'
        sheet_name (str): The name of the worksheet to load (e.g., 'Sheet1', 'Tabelle1').
                          Defaults to 'Sheet1'.

    Returns:
        pandas.DataFrame: A DataFrame containing the data from the specified worksheet,
                          or None if an error occurs.
    """
    # 1. Authenticate with Google Colab
    auth.authenticate_user()

    # 2. Authorize gspread to access your Google Drive/Sheets
    try:
        creds, _ = default()
        gc = gspread.authorize(creds)
    except Exception as e:
        print(f"Error during gspread authorization: {e}")
        return None

    # 3. Extract the Google Sheet's document name from the file_path
    # .gsheet files are shortcuts and cannot be opened directly from the filesystem.
    # We extract the base name and assume it's the title of the Google Sheet.
    base_name = os.path.basename(file_path) # e.g., 'sb_cm_input.gsheet'
    doc_name = os.path.splitext(base_name)[0] # e.g., 'sb_cm_input'

    if not doc_name:
        print(f"Error: Could not extract document name from file path: {file_path}")
        return None

    # 4. Open the Google Sheet by its title (document name)
    try:
        spreadsheet = gc.open(doc_name)
    except gspread.exceptions.SpreadsheetNotFound:
        print(f"Error: Google Sheet with title '{doc_name}' not found. Please ensure the name is correct and you have access.")
        return None
    except Exception as e:
        print(f"An error occurred while opening the spreadsheet: {e}")
        return None

    # 5. Select a worksheet
    try:
        worksheet = spreadsheet.worksheet(sheet_name)
    except gspread.exceptions.WorksheetNotFound:
        print(f"Error: Worksheet '{sheet_name}' not found in the spreadsheet. Available worksheets are: {[ws.title for ws in spreadsheet.worksheets()]}")
        return None
    except Exception as e:
        print(f"An error occurred while selecting the worksheet: {e}")
        return None

    # 6. Get all data as a list of lists
    data = worksheet.get_all_values()

    # 7. Convert to a Pandas DataFrame
    if data:
        df = pd.DataFrame(data[1:], columns=data[0]) # Assuming the first row is the header
        print("DataFrame created successfully:")
        print(df.head())
        return df.to_dict('records')
    else:
        print(f"No data found in the worksheet '{sheet_name}'.")
        return pd.DataFrame() # Return empty DataFrame if no data

