def read_google_doc_content(drive_path: str) -> str:
    """
    Liest den Inhalt eines Google Docs-Dokuments, das durch seinen Drive-Pfad angegeben ist,
    und gibt ihn als einfachen String zurück.

    Args:
        drive_path (str): Der vollständige Pfad zum Google Docs-Dokument in Google Drive,
                          z.B. '/content/drive/MyDrive/MyFolder/MyDocument.gdoc'.
                          Die Funktion extrahiert den Basisnamen (ohne .gdoc-Erweiterung)
                          als Dokumenttitel, um in Drive zu suchen.

    Returns:
        str: Der reine Textinhalt des Google Docs-Dokuments.

    Raises:
        ValueError: Wenn das Dokument nicht gefunden oder nicht zugegriffen werden kann.
        HttpError: Für andere Google API-Fehler.
    """
    # Benutzer authentifizieren
    auth.authenticate_user()
    credentials, _ = default()

    # Drive API-Dienst erstellen
    drive_service = build('drive', 'v3', credentials=credentials)

    # Dokumenttitel aus dem Pfad extrahieren
    doc_title = os.path.splitext(os.path.basename(drive_path))[0]

    file_id = None
    try:
        # Suche nach Dateien mit dem exakten Namen und Google Docs mimeType
        # 'application/vnd.google-apps.document'
        query = f"name='{doc_title}' and mimeType='application/vnd.google-apps.document'"
        results = drive_service.files().list(q=query, fields="files(id, name)").execute()
        items = results.get('files', [])

        if not items:
            raise ValueError(f"Google Docs-Dokument '{doc_title}' in Drive nicht gefunden.")
        elif len(items) > 1:
            print(f"Warnung: Mehrere Google Docs mit dem Titel '{doc_title}' gefunden. Verwende das erste gefundene (ID: {items[0]['id']}).")

        file_id = items[0]['id']

    except HttpError as error:
        raise ValueError(f"Fehler bei der Suche nach Dokument '{doc_title}': {error}") from error

    if not file_id:
        raise ValueError(f"Konnnte keine Datei-ID für Dokument '{doc_title}' ermitteln.")

    # Inhalt des Dokuments als reinen Text exportieren
    try:
        request = drive_service.files().export(fileId=file_id, mimeType='text/plain')
        content_bytes = request.execute()
        content_string = content_bytes.decode('utf-8')
        return content_string
    except HttpError as error:
        raise ValueError(f"Fehler beim Exportieren des Inhalts für Dokument-ID '{file_id}': {error}") from error

