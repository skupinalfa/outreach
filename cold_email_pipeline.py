def resolve_domain(
    company: str,
    api_key: Optional[str] = None,
    perfect_match: bool = True,
) -> Optional[str]:
    """Resolve a company name to its most likely domain (Domain Finder, free).

    perfect_match=True returns only high-similarity matches, so you get one
    confident answer instead of a candidate list. Returns None if unresolved.
    """
    if len(company) < 3:
        raise ValueError("Domain Finder requires at least 3 characters.")

    data = _get(
        "domain-finder",
        {"company": company, "limit": 1, "perfect_match": str(perfect_match).lower()},
        api_key,
    ).get("data", [])

    return data[0]["domain"] if data else None


def find_email(
    first_name: str,
    last_name: str,
    company: str,
    api_key: Optional[str] = None,
    resolve_first: bool = True,
) -> dict:
    """Look up a work email for a person at a company.

    `company` may be a plain company name ("Stripe") or a domain
    ("stripe.com"). With resolve_first=True, a company name is first sent
    through the free Domain Finder so the lookup runs against an explicit
    domain — more accurate, and you can see which domain was used.

    Returns: email, domain, score, position, verification_status,
    source_count, resolved_domain. `email` is None when nothing is found.
    """
    looks_like_domain = "." in company and " " not in company
    params = {"first_name": first_name, "last_name": last_name}
    resolved = None

    if looks_like_domain:
        params["domain"] = company
    elif resolve_first:
        resolved = resolve_domain(company, api_key)
        # Fall back to Hunter's own conversion if the name doesn't resolve.
        if resolved:
            params["domain"] = resolved
        else:
            params["company"] = company
    else:
        params["company"] = company
    if not resolved:
      return {
        "email": "Not in Hunter",
        "domain": "Not in Hunter",
        "score": "Not in Hunter",
        "position": "Not in Hunter",
        "verification_status": "Not in Hunter",
        "source_count": "Not in Hunter",
        "resolved_domain": "Not in Hunter",
    }
    data = _get("email-finder", params, api_key).get("data", {})

    return {
        "email": data.get("email"),
        "domain": data.get("domain"),
        "score": data.get("score"),
        "position": data.get("position"),
        "verification_status": (data.get("verification") or {}).get("status"),
        "source_count": len(data.get("sources", [])),
        "resolved_domain": resolved,
    }


def find_emails_to_csv(
    people: Iterable[tuple[str, str, str]],
    path: str = "emails.csv",
    api_key: Optional[str] = None,
) -> str:
    """Run find_email over (first_name, last_name, company) tuples and write
    email + domain to a CSV. Failures are recorded per row, not raised."""
    fields = [
        "first_name", "last_name", "company",
        "email", "domain", "score", "verification_status", "error",
    ]

    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()

        for first, last, company in people:
            row = {"first_name": first, "last_name": last, "company": company}
            try:
                result = find_email(first, last, company, api_key)
                row.update({k: v for k, v in result.items() if k in fields})
            except Exception as exc:  # network error, rate limit, bad key
                row["error"] = str(exc)
            writer.writerow(row)

    return path

