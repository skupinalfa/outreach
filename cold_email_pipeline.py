class RetryableOpenAIAPIError(Exception):
    """OpenAI-API-Fehler, bei dem ein erneuter Versuch sinnvoll ist."""


class NonRetryableOpenAIAPIError(Exception):
    """OpenAI-API-Fehler, bei dem ein erneuter Versuch nicht sinnvoll ist."""


def _resolve_api_key(api_key: str | None = None) -> str:
    if api_key:
        return api_key
    if userdata is not None:
        # Achtung: userdata.get() nimmt kein Default-Argument und wirft
        # bei fehlendem Secret eine Exception, statt None zurückzugeben.
        try:
            api_key = userdata.get("OPENAI_API_KEY")
        except Exception:
            api_key = None
    api_key = api_key or os.environ.get("OPENAI_API_KEY")
    if not api_key:
        raise NonRetryableOpenAIAPIError(
            "OpenAI API-Schlüssel nicht gefunden. Bitte als 'OPENAI_API_KEY' im "
            "Colab-Geheimnis-Manager hinterlegen oder direkt übergeben."
        )
    return api_key


def _extract_text(response) -> str:
    # Bequemer Weg: das SDK aggregiert alle Text-Blöcke selbst.
    text = getattr(response, "output_text", None)
    if text:
        return text

    # Fallback: manuell über die Output-Items laufen.
    parts = []
    for entry in getattr(response, "output", []):
        if getattr(entry, "type", None) != "message":
            continue
        content = entry.content
        if isinstance(content, str):
            parts.append(content)
        else:
            for chunk in content:
                if getattr(chunk, "type", None) == "output_text":
                    chunk_text = getattr(chunk, "text", None)
                    if chunk_text:
                        parts.append(chunk_text)
    return "\n".join(parts)


def call_openai_with_web_search(
    prompt: str,
    api_key: str | None = None,
    model: str = "gpt-5.6-luna",
    max_tokens: int = 10000,
) -> str:
    key = _resolve_api_key(api_key)

    try:
        with OpenAI(api_key=key) as client:
            response = client.responses.create(
                model=model,
                input=prompt,
                tools=[{"type": "web_search"}],
                max_output_tokens=max_tokens,
            )
        return _extract_text(response)

    except openai.RateLimitError as e:
        raise RetryableOpenAIAPIError(f"Rate Limit überschritten: {e}") from e
    except openai.APIStatusError as e:
        status = e.status_code
        if 500 <= status < 600:
            raise RetryableOpenAIAPIError(f"Serverfehler ({status}): {e}") from e
        raise NonRetryableOpenAIAPIError(f"Clientfehler ({status}): {e}") from e

    except openai.APITimeoutError as e:
        raise RetryableOpenAIAPIError(f"Timeout-Fehler: {e}") from e
    except openai.APIConnectionError as e:
        raise RetryableOpenAIAPIError(f"Verbindungsfehler: {e}") from e

    # Falls httpx direkt durchschlägt (z. B. eigener http_client).
    except (httpx.ConnectError, httpx.TimeoutException) as e:
        raise RetryableOpenAIAPIError(f"Verbindungs-/Timeout-Fehler: {e}") from e
    except httpx.RequestError as e:
        raise RetryableOpenAIAPIError(f"Netzwerkfehler: {e}") from e
    except Exception as e:
        raise NonRetryableOpenAIAPIError(f"Unerwarteter Fehler: {e}") from e

