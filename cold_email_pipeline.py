def build_prompt(
    prompt_template: str,
    input_dict:dict,
    strict: bool = True,
    mail_template: str = None,
) -> str:
    """Substitute {domain}, {name}, {gender} and {mail_template} into the template.

    Deliberately uses str.replace instead of str.format: mail templates often
    contain their own curly braces, which .format() would treat as placeholders
    and reject with KeyError or ValueError.
    """
    values = {
        "domain": input_dict["domain"],
        "last_name": input_dict["last_name"],
        "gender": input_dict["gender"],
        "template": mail_template,
    }

    if strict:
        missing = [f for f in PROMPT_FIELDS if "{" + f + "}" not in prompt_template]
        if missing:
            raise ValueError(
                "Placeholders missing from prompt template: "
                + ", ".join("{" + f + "}" for f in missing)
            )

    result = prompt_template
    for key, value in values.items():
        result = result.replace("{" + key + "}", str(value))
    return result

